"""Phase 1A: build data/processed/docs.jsonl (one record per spreadsheet row) and coverage_report.md.

Text source priority per row:
  1. fr_text   : full text fetched from the Federal Register API (cached)
  2. embedded  : regulatory text that leaked into the spreadsheet's link column (not a URL)
  3. summary   : only the spreadsheet Summary field (flagged coverage = summary_only)
"""
import json
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ingest  # noqa: E402
from parse_sections import parse_document, load_doc  # noqa: E402

PROCESSED = ingest.PROCESSED
NUM = re.compile(r"(\d{3,6})")


def start_page(page_field) -> int | None:
    m = NUM.search(str(page_field or ""))
    return int(m.group(1)) if m else None


def main():
    df = ingest.load_index()
    recs = []
    for _, r in df.iterrows():
        link = r["Link for Submitting Public Comment"]
        text, source = None, "summary"
        if isinstance(r["doc_number"], str):
            t = load_doc(r["doc_number"])
            if t:
                text, source = t, "fr_text"
        if text is None and link and not link.startswith("http") and len(link) > 100:
            text, source = link, "embedded"
            if "\\n" in text and text.count("\n") < 3:  # cell stored literal backslash-n sequences
                text = text.replace("\\n", "\n").replace("\\t", "\t")
        sp = start_page(r["Page Number"])
        parsed = parse_document(text, sp) if text else {"sections": {}, "is_withdrawal": False, "has_reg_text": False}
        summ = str(r["Summary"]) if isinstance(r["Summary"], str) else ""
        is_wd = parsed["is_withdrawal"] or bool(re.search(r"\bis withdrawing\b|\bNPRM is withdrawn\b", summ, re.I))
        recs.append({
            "doc_id": r["doc_id"], "doc_number": r["doc_number"] if isinstance(r["doc_number"], str) else None,
            "docket": r["Docket Number"], "subject": r["Subject Heading"], "make_raw": r["Make"], "make_norm": r["make_norm"],
            "models": [m.strip() for m in str(r["Model"]).split("|")] if isinstance(r["Model"], str) else [],
            "product_type": r["Product Type"] if isinstance(r["Product Type"], str) else None,
            "cfr_part": r["CFR Part Reference"], "issue_date": r["issue_iso"],
            "citation": r["Citation"], "page_field": r["Page Number"], "start_page": sp,
            "comments": r["Comments"] if isinstance(r["Comments"], str) else None,
            "comments_due": r["Comments Due Date"] if isinstance(r["Comments Due Date"], str) else None,
            "summary": summ, "source": source, "text": text, "sections": parsed["sections"],
            "has_reg_text": parsed["has_reg_text"], "is_withdrawal": is_wd,
        })
    PROCESSED.mkdir(parents=True, exist_ok=True)
    with open(PROCESSED / "docs.jsonl", "w", encoding="utf-8") as f:
        for x in recs:
            f.write(json.dumps(x, ensure_ascii=False) + "\n")

    n = len(recs)
    src = Counter(x["source"] for x in recs)
    c_found = Counter(x["source"] for x in recs if "c" in x["sections"])
    wd = Counter(x["source"] for x in recs if x["is_withdrawal"])
    full = src["fr_text"] + src["embedded"]
    lines = [
        "# Coverage report (generated by src/build_corpus.py)", "",
        f"- Spreadsheet rows: **{n}**",
        f"- Rows with a resolved FR document number: **{sum(1 for x in recs if x['doc_number'])}** "
        f"({len({x['doc_number'] for x in recs if x['doc_number']})} unique documents)",
        f"- Text source: fr_text **{src['fr_text']}**, embedded (link column) **{src['embedded']}**, summary_only **{src['summary']}**",
        f"- **Full-text coverage: {full}/{n} = {100 * full / n:.1f}%**",
        f"- Withdrawal notices detected: **{sum(wd.values())}** (fr_text {wd['fr_text']}, embedded {wd['embedded']}, summary {wd['summary']})",
        f"- Rows with any lettered sections parsed: {sum(1 for x in recs if x['sections'])}",
        f"- Part 39: {sum(1 for x in recs if x['cfr_part'] == 'Part 39')}, other part: {sum(1 for x in recs if x['cfr_part'] != 'Part 39')}",
    ]
    (PROCESSED / "coverage_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
