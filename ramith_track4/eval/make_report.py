"""Generate eval/results/REPORT.md and eval/results/latest.json from the SAVED result files only (no hand-typed numbers).

Inputs (all under eval/results/):
  FIRSTPASS_blind_B1_B2_full.json, FIRSTPASS_validation_B1b_B2b_full.json, ..._B1c_B2c..., ..._B1d_B2d..., ..._B1e_B2e...
  V1_HELDOUT_TEST_all_systems.json, BASELINES_final_B2c_B2e.json, extraction_audit.md
"""
import json
import math
from pathlib import Path

R = Path(__file__).resolve().parent / "results"


def load(n):
    return json.loads((R / n).read_text(encoding="utf-8"))


def fsha(name):
    import hashlib
    return hashlib.sha256((R.parent / "blind" / name).read_bytes().replace(b"\r\n", b"\n")).hexdigest()[:12]


def wilson(k, n, z=1.96):
    if not n:
        return (None, None)
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (round(100 * (c - h) / d, 1), round(100 * (c + h) / d, 1))


def fmt(k, n):
    if not n:
        return "n/a"
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {100 * k / n:.1f}% (95% CI {lo}-{hi})"


SETS = [("B1/B2", "FIRSTPASS_blind_B1_B2_full.json", "b1", "b2"), ("B1b/B2b", "FIRSTPASS_validation_B1b_B2b_full.json", "b1b", "b2b"),
        ("B1c/B2c", "FIRSTPASS_validation_B1c_B2c_full.json", "b1c", "b2c"), ("B1d/B2d", "FIRSTPASS_validation_B1d_B2d_full.json", "b1d", "b2d"),
        ("B1e/B2e", "FIRSTPASS_validation_B1e_B2e_full.json", "b1e", "b2e")]


def cat(rows, c):
    r = [x for x in rows if x["category"] == c]
    return sum(x["ok"] for x in r), len(r)


def main():
    out = ["# Evaluation report (generated by eval/make_report.py from saved result files)", ""]
    meta_lines, tableA, pooled_b1, pooled_b2 = [], [], [0, 0], {k: [0, 0] for k in ("lookup", "applicability", "revision", "refuse")}
    ref_tp = ref_n = ref_should = ref_tp_all = 0
    for name, f, k1, k2 in SETS:
        d = load(f)
        m = d["meta"]
        b1 = d["results"][f"{k1}/full"]["rows"]
        b2 = d["results"][f"{k2}/full"]["rows"]
        ok1 = sum(x["ok"] for x in b1)
        pooled_b1[0] += ok1
        pooled_b1[1] += len(b1)
        cells = [fmt(*cat(b2, c)) .split(" (")[0] for c in ("lookup", "applicability", "revision", "refuse")]
        for c in pooled_b2:
            kk, nn = cat(b2, c)
            pooled_b2[c][0] += kk
            pooled_b2[c][1] += nn
        refused = [x for x in b2 if x["refused"]]
        tp = sum(1 for x in refused if x["category"] == "refuse")
        ref_tp += tp
        ref_n += len(refused)
        ref_should += sum(1 for x in b2 if x["category"] == "refuse")
        tableA.append(f"| {name} | `{m['src_hash']}` | {ok1}/{len(b1)} = {100 * ok1 / len(b1):.1f}% | " + " | ".join(cells) + f" | {tp}/{len(refused)} |")
    out += ["## 1. First-pass results on data the system had never seen",
            "Each row is the FIRST and only pass of that system version on freshly generated data (frozen by hash before the run). "
            "Between rows the system was changed to fix the failures found in the previous row, so rows are different system versions (see `src_hash`).",
            "",
            "| Set | system src hash | fresh-document engine (verdict acc.) | lookup | applicability (free text) | revision | refuse (recall) | refusals that were right |",
            "|---|---|---|---|---|---|---|---|"] + tableA + [""]
    out += ["**Pooled over the five first-pass rows** (mixed system versions; use as a rough generalisation estimate, not a property of one version):", ""]
    out.append(f"- Fresh-document engine verdict accuracy: {fmt(*pooled_b1)}")
    for c, (k, n) in pooled_b2.items():
        out.append(f"- B2 {c}: {fmt(k, n)}")
    out.append(f"- Refusal precision (all B2 refusals that were labelled refuse): {fmt(ref_tp, ref_n)}")
    out += ["", "The first-pass accuracy on fresh documents did NOT trend upward across rows while fixes were being made "
            "(the failures are long-tailed), so the per-failure fixes should not be read as proof of better generalisation.", ""]

    # latest untouched
    e = load("FIRSTPASS_validation_B1e_B2e_full.json")
    es = e["results"]["b2e/full"]["summary"]
    e1 = e["results"]["b1e/full"]["summary"]
    out += ["## 2. Final system on the last untouched set (e)", "",
            f"- final system src hash `{e['meta']['src_hash']}` (system commit 93576dd); B1e sha256 `{fsha('blind_B1e.jsonl')}`, B2e sha256 `{fsha('blind_B2e.jsonl')}` (computed from the files; "
            "the run metadata's B1/B2 hash fields refer to the first set and are not used)",
            f"- fresh-document engine: verdict accuracy {e1['verdict_accuracy']}%, reason accuracy {e1['reason_accuracy']}%, per gold verdict {e1['per_gold']}, confusion {e1['confusion']}",
            f"- B2e: lookup {es['lookup']['pct']}%, applicability {es['applicability']['pct']}% (reason {es['applicability']['reason_accuracy']}%), revision {es['revision']['pct']}%, "
            f"refusal recall {es['refusal']['recall']}% / precision {es['refusal']['precision']}% / code accuracy {es['refusal']['code_accuracy']}%",
            f"- unsupported-quote rate {es.get('unsupported_quote_rate_pct')}%, latency p50/p95 {es.get('latency_ms_total')}", ""]

    # baselines
    out += ["## 3. Baselines (same questions)", ""]
    bf = load("BASELINES_final_B2c_B2e.json")
    v1 = load("V1_HELDOUT_TEST_all_systems.json")
    full_c = load("FIRSTPASS_validation_B1c_B2c_full.json")["results"]["b2c/full"]["summary"]
    full_e = es
    out.append("| Set | System | lookup | applicability | revision | refuse recall | refuse precision | cited IDs not in corpus |")
    out.append("|---|---|---|---|---|---|---|---|")

    def row(setn, sysn, s):
        ci = s.get("llm_cited_ids", {}).get("pct_not_in_corpus", "-")
        prec = "n/a (never refuses)" if s["refusal"]["precision"] is None else f"{s['refusal']['precision']}%"
        out.append(f"| {setn} | {sysn} | {s['lookup']['pct']}% | {s['applicability']['pct']}% | {s['revision']['pct']}% | {s['refusal']['recall']}% | {prec} | {ci} |")
    row("B2c", "full system", full_c)
    row("B2e", "full system", full_e)
    for key, v in bf["results"].items():
        sn, sy = key.split("/")
        if sn.startswith("b2"):
            row(sn[0].upper() + sn[1:], sy, v["summary"])
    for sy in ("full", "naive_summary", "fulltext_bm25", "llm_only", "llm_forced"):
        v = v1["results"].get(f"v1test/{sy}")
        if v:
            row("v1 held-out (not blind)", sy, v["summary"])
    kb = [v["summary"]["verdict_accuracy"] for k, v in bf["results"].items() if k.startswith("b1e")]
    out += ["", f"Fresh-document set B1e: our engine {e1['verdict_accuracy']}% vs a keyword baseline (APPLIES if the model string appears anywhere in the notice, else DOES_NOT_APPLY, never CANNOT_DETERMINE) {kb[0] if kb else 'n/a'}%.", "",
        "Notes: (a) lookup and revision questions were written by the annotator from each notice's own wording, so plain BM25 solves them too; "
        "they do not discriminate between systems. (b) Set c's six revision questions were all 'withdrawn', so a base-rate guess scores 100% there. "
        "(c) LLM baselines are non-deterministic and n is small; `llm_only` was told it has no documents and so declines most questions; "
        "`llm_forced` must answer and cites document numbers that mostly do not exist (the 'cited IDs not in corpus' column). "
        "(d) The LLM baselines are scored on their own words for revision, and applicability ignores which document they cite (generous to them).", ""]

    # v1 vs blind
    vf = v1["results"]["v1test/full"]["summary"]
    out += ["## 4. Not-blind vs blind: the overfitting gap", "",
            f"- Held-out v1 test set (30 questions, **written by the builder**, run once with `--final`, system src hash `{v1['meta']['src_hash']}`): "
            f"lookup {vf['lookup']['pct']}%, applicability {vf['applicability']['pct']}%, revision {vf['revision']['pct']}%, refusal recall {vf['refusal']['recall']}%.",
            f"- Independent-annotator blind data (rows in section 1): fresh-document engine pooled {fmt(*pooled_b1)}; free-text applicability pooled {fmt(*pooled_b2['applicability'])}.",
            "- The v1 numbers are optimistic: the builder wrote the questions, read the documents, and wrote rules from the same corpus. Quote the blind numbers.", ""]
    out += ["## 5. Extraction audit (hand-checked, single reviewer)", "", "See `extraction_audit.md` (four rounds, including failures).", ""]
    out += ["## 6. What fails and how a user would know", "",
            "- **Over-caution (most common):** the system says CANNOT_DETERMINE where the annotator said APPLIES: notes under (c) that mention 'with ...', "
            "an exclusion that applies to a different model than the user's, '-XX' wildcard part numbers, notices that name the model but defer to a foreign AD. "
            "The user sees the quoted clause and the reason code.",
            "- **Silent wrong 'applies' (rare, most dangerous):** a certificate-date condition missed because the notice text wraps lines mid-phrase (found on B1d, fixed afterwards). "
            "Nothing on the card flags this; the user would only see the applicability paragraph quoted with a MODEL_LISTED verdict. "
            "Mitigation shipped: the quoted applicability paragraph is always shown next to the verdict so a qualified person can read the actual condition.",
            "- **Not handled:** serial ranges are per document not per model group; informal model names that differ from the notice ('King Air 350' vs 'Model B300'); "
            "applicability defined in outside documents (by design: refused or CANNOT_DETERMINE).",
            "- **Refusal codes** are right only about 70-90% of the time even when the refusal itself is right.", ""]
    (R / "REPORT.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    (R / "latest.json").write_text(json.dumps({"markdown": "\n".join(out)}, ensure_ascii=False), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
